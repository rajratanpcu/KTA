// Helper functions
export function getTransporterById(id: string): Transporter | undefined {
  return demoTransporters.find(t => t.id === id)
}

export function getBillsByTransporter(transporterId: string): TransportBill[] {
  return demoTransportBills.filter(b => b.transporterId === transporterId)
}

export function getPaymentsByTransporter(transporterId: string): TransportPayment[] {
  return demoTransportPayments.filter(p => p.transporterId === transporterId)
}

export function calculateBillSummary() {
  const total = demoTransportBills.length
  const totalAmount = demoTransportBills.reduce((sum, b) => sum + b.totalAmount, 0)
  const totalPaid = demoTransportBills.reduce((sum, b) => sum + b.amountPaid, 0)
  const outstanding = totalAmount - totalPaid
  const unpaid = demoTransportBills.filter(b => b.status === 'PENDING').length
  const partiallyPaid = demoTransportBills.filter(b => b.status === 'PARTIALLY_PAID').length
  const paid = demoTransportBills.filter(b => b.status === 'PAID').length

  return {
    total,
    totalAmount,
    totalPaid,
    outstanding,
    unpaid,
    partiallyPaid,
    paid,
  }
}
