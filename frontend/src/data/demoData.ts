// Helper to get stock balance for a product at a godown
export function getStockBalance(productId: string, godownId: string): StockBalance | undefined {
  return demoStockBalances.find(
    (sb) => sb.productId === productId && sb.godownId === godownId
  )
}

// Helper to get total stock for a product across all godowns
export function getTotalStock(productId: string): number {
  return demoStockBalances
    .filter((sb) => sb.productId === productId)
    .reduce((sum, sb) => sum + sb.availableQuantity, 0)
}
